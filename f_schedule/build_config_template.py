HDRFILL = PatternFill("solid", fgColor="365F91")


def _style_header(ws, ncol):
    for c in range(1, ncol + 1):
        cell = ws.cell(1, c)
        cell.font = HDR
        cell.fill = HDRFILL
        cell.alignment = Alignment(horizontal="center", vertical="center")


